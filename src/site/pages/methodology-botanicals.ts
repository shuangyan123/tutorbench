export function renderMethodologyBotanical(placement: BotanicalPlacement): string {
  const { stems, leaves } = compositions[placement];
  const className = placement === "hero" ? "method-botanical-left" : `method-scope-botanical method-scope-botanical--${placement}`;
  // 每组叶片从叶柄起笔；轮廓、中脉和侧脉共用坐标，避免装饰枝条与叶片脱节。
  return `<svg class="method-botanical ${className}" viewBox="0 0 360 440" aria-hidden="true" focusable="false" shape-rendering="geometricPrecision">
    <g fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">
      <path class="method-botanical-stem" d="${stems}"/>
      ${leaves.map(({ outline, midrib, veins }) => `<g class="method-botanical-leaf"><path class="method-botanical-outline" d="${outline}"/><path class="method-botanical-midrib" d="${midrib}"/><path class="method-botanical-veins" d="${veins}"/></g>`).join("\n      ")}
    </g>
  </svg>`;
}
